import { useQuery } from "@tanstack/react-query";
import { motion } from "framer-motion";
import { Activity, Database, HardDrive, Server } from "lucide-react";
import { fetchSystemHealth } from "../services/api";
import { Card } from "../components/ui/Card";
import { Badge } from "../components/ui/Badge";

export function SystemHealth() {
  const { data, isLoading, error } = useQuery({ queryKey: ["system-health"], queryFn: fetchSystemHealth });

  if (isLoading) return <div className="text-sm text-slate-500">Loading platform health...</div>;
  if (error || !data) return <div className="text-sm text-red-600">System health API is not available.</div>;

  return (
    <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="space-y-4">
      <div className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm dark:border-slate-700 dark:bg-slate-900">
        <div className="flex flex-col gap-2">
          <div>
            <h1 className="text-xl font-bold text-slate-900 dark:text-white">Platform Health</h1>
            <p className="text-sm text-slate-500 dark:text-slate-400">Server-side service and backend health metrics for the deployed toll detection platform.</p>
          </div>
          <p className="text-xs text-slate-400">These values are generated by the backend service, not by the visitor's local laptop.</p>
        </div>
      </div>

      <section className="grid grid-cols-2 gap-3 md:grid-cols-4">
        <Metric label="Overall Health" value={data.overall_health ?? "Unknown"} icon={Activity} />
        <Metric label="Services" value={String(data.services?.length ?? 0)} icon={Server} />
        <Metric label="Database" value={data.services?.find((s: any) => s.name === "Database Connection")?.status ?? "Unknown"} icon={Database} />
        <Metric label="CPU" value={data.system_metrics?.cpu ?? "Unknown"} icon={HardDrive} />
      </section>

      <Card className="p-3">
        <h3 className="mb-3 text-sm font-bold">Backend Services</h3>
        <div className="overflow-x-auto">
          <table className="w-full text-[11px]">
            <thead>
              <tr className="border-b border-slate-100 text-left text-slate-400">
                <th className="pb-2 pr-2 font-semibold">Name</th>
                <th className="pb-2 pr-2 font-semibold">Status</th>
                <th className="pb-2 pr-2 font-semibold">Uptime</th>
                <th className="pb-2 font-semibold">Response</th>
              </tr>
            </thead>
            <tbody>
              {(data.services ?? []).map((service: any) => (
                <tr key={service.name} className="border-b border-slate-50">
                  <td className="py-2 pr-2 font-semibold">{service.name}</td>
                  <td className="py-2 pr-2"><Badge tone={service.status === "Online" ? "green" : "red"}>{service.status}</Badge></td>
                  <td className="py-2 pr-2 text-slate-500">{service.uptime}</td>
                  <td className="py-2 text-slate-500">{service.response}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>

      <Card className="p-3">
        <h3 className="mb-3 text-sm font-bold">Server Metrics</h3>
        <div className="grid gap-3 text-xs md:grid-cols-4">
          {Object.entries(data.system_metrics ?? {}).map(([key, value]) => (
            <div key={key} className="rounded border border-slate-100 p-3 dark:border-slate-800">
              <p className="capitalize text-slate-400">{key}</p>
              <p className="mt-1 font-bold">{String(value)}</p>
            </div>
          ))}
        </div>
      </Card>
    </motion.div>
  );
}

function Metric({ label, value, icon: Icon }: { label: string; value: string; icon: typeof Activity }) {
  return (
    <Card className="p-3">
      <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-teal-500/10 text-teal-600">
        <Icon size={16} />
      </div>
      <p className="mt-2 text-lg font-bold">{value}</p>
      <p className="text-[11px] font-semibold text-slate-500">{label}</p>
    </Card>
  );
}

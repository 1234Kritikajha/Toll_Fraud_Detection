import { useQuery } from "@tanstack/react-query";
import { motion } from "framer-motion";
import { Car, History, Search, ShieldAlert } from "lucide-react";
import { useState } from "react";
import { fetchVehicle, fetchVehicleHistory } from "../services/api";
import { Card } from "../components/ui/Card";
import { Button } from "../components/ui/Button";
import { Badge } from "../components/ui/Badge";

export function VehicleIntelligence() {
  const [vehicleQuery, setVehicleQuery] = useState("");
  const [submittedPlate, setSubmittedPlate] = useState("");

  const vehicle = useQuery({
    queryKey: ["vehicle", submittedPlate],
    queryFn: () => fetchVehicle(submittedPlate),
    enabled: Boolean(submittedPlate),
    retry: false,
  });

  const history = useQuery({
    queryKey: ["vehicle-history", submittedPlate],
    queryFn: () => fetchVehicleHistory(submittedPlate),
    enabled: Boolean(submittedPlate),
  });

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setSubmittedPlate(vehicleQuery.trim().toUpperCase());
  };

  return (
    <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="space-y-4">
      <form onSubmit={handleSubmit} className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-slate-100 bg-white p-3 shadow-sm dark:border-slate-800 dark:bg-[#0d1b2e]">
        <div className="flex items-center gap-2">
          <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-teal-500/10 text-teal-600">
            <Car size={16} />
          </div>
          <div>
            <h2 className="text-sm font-bold leading-tight">Vehicle Profile Analysis</h2>
            <p className="text-[10px] text-slate-400">Search your saved vehicle registry and detection history</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <div className="flex items-center gap-2 rounded border border-slate-200 bg-slate-50 px-2 py-1 dark:border-slate-700 dark:bg-slate-850">
            <Search size={12} className="text-slate-400" />
            <input
              type="text"
              value={vehicleQuery}
              onChange={(e) => setVehicleQuery(e.target.value)}
              className="bg-transparent text-[11px] font-semibold uppercase outline-none placeholder:text-slate-400"
              placeholder="Search vehicle number..."
            />
          </div>
          <Button size="sm" className="h-7 bg-teal-600 text-xs text-white">Analyze</Button>
        </div>
      </form>

      {!submittedPlate && (
        <Card className="p-8 text-center text-sm text-slate-400">Enter a vehicle number to load records from your database.</Card>
      )}

      {submittedPlate && vehicle.error && (
        <Card className="p-8 text-center text-sm text-slate-400">No vehicle registry record found for {submittedPlate}.</Card>
      )}

      {vehicle.data && (
        <section className="grid gap-3 xl:grid-cols-[1fr_1fr]">
          <Card className="p-3">
            <h3 className="mb-3 text-sm font-bold">Vehicle Profile</h3>
            <div className="grid grid-cols-2 gap-3 text-xs">
              <Field label="Plate" value={vehicle.data.plate} />
              <Field label="FASTag ID" value={vehicle.data.fastag_id || "-"} />
              <Field label="Make" value={vehicle.data.make || "-"} />
              <Field label="Model" value={vehicle.data.model || "-"} />
              <Field label="Color" value={vehicle.data.color || "-"} />
              <div>
                <p className="text-slate-400">Blacklist Status</p>
                <Badge tone={vehicle.data.is_blacklisted ? "red" : "green"}>{vehicle.data.is_blacklisted ? "Blacklisted" : "Clear"}</Badge>
              </div>
            </div>
          </Card>

          <Card className="p-3">
            <h3 className="mb-3 flex items-center gap-2 text-sm font-bold"><ShieldAlert size={16} /> Database Risk Signals</h3>
            <p className="text-xs text-slate-500">
              This panel uses your database only. Risk alerts are generated by the backend when YOLO/OCR detections are uploaded and fraud rules match database records.
            </p>
          </Card>
        </section>
      )}

      {submittedPlate && (
        <Card className="p-3">
          <h3 className="mb-3 flex items-center gap-2 text-sm font-bold"><History size={16} /> Travel History</h3>
          <div className="overflow-x-auto">
            <table className="w-full text-[11px]">
              <thead>
                <tr className="border-b border-slate-100 text-left text-slate-400">
                  <th className="pb-2 pr-2 font-semibold">Time</th>
                  <th className="pb-2 pr-2 font-semibold">Plaza</th>
                  <th className="pb-2 pr-2 font-semibold">Lane</th>
                  <th className="pb-2 pr-2 font-semibold">Status</th>
                  <th className="pb-2 font-semibold">Amount</th>
                </tr>
              </thead>
              <tbody>
                {(history.data ?? []).length === 0 && (
                  <tr>
                    <td colSpan={5} className="py-8 text-center text-sm text-slate-400">No transaction history found for this plate.</td>
                  </tr>
                )}
                {(history.data ?? []).map((row: any, index: number) => (
                  <tr key={`${row.time}-${index}`} className="border-b border-slate-50">
                    <td className="py-2 pr-2 text-slate-500">{row.time}</td>
                    <td className="py-2 pr-2 font-semibold">{row.plaza || "-"}</td>
                    <td className="py-2 pr-2 text-slate-500">{row.lane || "-"}</td>
                    <td className="py-2 pr-2">{row.status}</td>
                    <td className="py-2">{row.amount}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </Card>
      )}
    </motion.div>
  );
}

function Field({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <p className="text-slate-400">{label}</p>
      <p className="font-semibold">{value}</p>
    </div>
  );
}
